#!/usr/bin/env bash
#
# setup_realvnc.sh - install and start RealVNC Server headlessly on a macOS runner.
#
# WHY NOT APPLE'S OWN VNC
# -----------------------
# Apple Remote Management's daemons are Apple *platform binaries*. macOS TCC
# refuses screen-capture grants to platform binaries outside a real MDM
# enrolment:
#
#     tccd: Platform binary prompting is 'Deny' because: is Platform Binary
#
# so ARD listens, authenticates, and then serves a black framebuffer.
#
# RealVNC Server is a third-party binary, so that rule does not apply and a
# TCC.db row IS honoured. On macOS its CaptureMethod=0 path uses
# ScreenCaptureKit, so it also gives real frame rates instead of the ~5fps
# ceiling you get from polling `screencapture`.
#
# Config (per RealVNC's own parameter reference):
#   Authentication = VncAuth  <- "the only scheme that allows direct
#                                 connections from non-RealVNC VNC Viewers"
#                                 i.e. TigerVNC / Remmina
#   RfbPort        = pick a port; ARD already owns 5900
#   CaptureMethod  = 0 (ScreenCaptureKit on macOS 13+)
#
# Password must be written in RealVNC's obfuscated format - generated with the
# bundled `vncpasswd -print`, never by hand.

set -uo pipefail

PW="${1:-FarisMac2026}"
PORT="${2:-5901}"
APP="/Applications/VNC Server.app"

log()  { printf '  %s\n' "$*"; }
warn() { printf '  !! %s\n' "$*" >&2; }

echo "==> Installing RealVNC Server..."
if [ ! -d "$APP" ]; then
  brew install --cask vnc-server 2>&1 | tail -3 || warn "brew install failed"
fi
[ -d "$APP" ] || { warn "VNC Server.app is not present - cannot continue"; exit 1; }

# ---------------------------------------------------------------- locate bins
find_bin() {
  find "$APP/Contents" -type f -name "$1" -perm -u+x 2>/dev/null | head -1
}
VNCSERVER="$(find_bin vncserver)"
VNCPASSWD="$(find_bin vncpasswd)"
log "vncserver : ${VNCSERVER:-<not found>}"
log "vncpasswd : ${VNCPASSWD:-<not found>}"

if [ -z "$VNCSERVER" ]; then
  echo "--- everything executable in the bundle ---" >&2
  find "$APP/Contents" -type f -perm -u+x 2>/dev/null | head -30 >&2
  exit 1
fi

# ------------------------------------------------------- obfuscated password
echo "==> Generating obfuscated VNC password..."
OBF=""
if [ -n "$VNCPASSWD" ]; then
  for attempt in "-print" "-print -service" "-service -print" ""; do
    # shellcheck disable=SC2086
    OBF=$(printf '%s' "$PW" | "$VNCPASSWD" $attempt 2>/dev/null | tr -d '\r\n' || true)
    [ -n "$OBF" ] && { log "vncpasswd $attempt -> $OBF"; break; }
  done
fi
if [ -z "$OBF" ]; then
  warn "vncpasswd produced nothing; trying the documented DES-style obfuscation"
  # Classic VNC fixed-key obfuscation - still what several builds accept.
  OBF=$(printf '%s' "$PW" | perl -we '
    BEGIN { @k = unpack "C*", pack "H*", "23 82 107 06 35 78 88 07" }
    $_ = <>; chomp; s/^(.{8}).*/$1/; @p = unpack "C*", $_;
    foreach (@k) { printf "%02X", $_ ^ (shift @p || 0) } print "\n";')
  log "fallback -> $OBF"
fi

# ------------------------------------------------------------- TCC for RealVNC
# Discovered at runtime so it does not depend on the bundle layout.
EXTRA=""
BUNDLE_ID=$(defaults read "$APP/Contents/Info.plist" CFBundleIdentifier 2>/dev/null || true)
[ -n "$BUNDLE_ID" ] && EXTRA="$BUNDLE_ID|0"
for exe in $(find "$APP/Contents" -type f -perm -u+x 2>/dev/null | head -40); do
  EXTRA="$EXTRA,$exe|1"
done
log "bundle id: ${BUNDLE_ID:-<unknown>}"

echo "==> Granting Screen Recording / Accessibility to RealVNC..."
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EXTRA_CLIENTS="$EXTRA" "$SCRIPT_DIR/grant_tcc.sh" 2>&1 | tail -6 \
  || warn "TCC grant reported a problem (continuing)"

# ------------------------------------------------------------------ config
echo "==> Writing RealVNC config..."
mkdir -p /var/root/.vnc/config.d
cat > /var/root/.vnc/config.d/vncserver <<EOF
# Generated by setup_realvnc.sh
Authentication=VncAuth
Password=$OBF
RfbPort=$PORT
CaptureMethod=0
AcceptKeyEvents=1
AcceptPointerEvents=1
AlwaysShared=1
NeverShared=0
DisconnectClients=1
IdleTimeout=0
AuthTimeout=0
BlacklistThreshold=0
# ARD already owns 5900; keep both alive side by side.
AllowIpListenRfb=1
localhost=0
Log=*:stderr:30
EOF
chmod 600 /var/root/.vnc/config.d/vncserver
log "wrote /var/root/.vnc/config.d/vncserver (RfbPort=$PORT)"

# ------------------------------------------------------------------- start
echo "==> Starting RealVNC Server..."
sudo launchctl unload /Library/LaunchDaemons/com.realvnc.vncserver.plist 2>/dev/null || true
sudo launchctl load   /Library/LaunchDaemons/com.realvnc.vncserver.plist 2>/dev/null \
  || log "no system LaunchDaemon - will start the binary directly"

# Service mode first, then user mode as a fallback (some cask builds differ).
sudo "$VNCSERVER" -start >/tmp/rv-start.log 2>&1
log "service-mode start rc=$?"
sleep 4

if ! sudo lsof -nP -iTCP:"$PORT" -sTCP:LISTEN >/dev/null 2>&1; then
  warn "nothing on $PORT after service mode; trying user mode in the GUI session"
  CU=$(stat -f '%Su' /dev/console); CUID=$(stat -f '%u' /dev/console)
  sudo launchctl asuser "$CUID" sudo -u "$CU" "$VNCSERVER" -start >/tmp/rv-user.log 2>&1
  log "user-mode start rc=$?"
  sleep 4
fi

echo "==> Listeners:"
sudo lsof -nP -iTCP -sTCP:LISTEN 2>/dev/null | grep -E ':59[0-9][0-9]' || warn "no VNC listener"
echo "==> Processes:"
pgrep -fl -i vnc | head -5 || warn "no vnc process"
echo "==> start log:"
tail -20 /tmp/rv-start.log 2>/dev/null || true
echo "==> user start log:"
tail -20 /tmp/rv-user.log 2>/dev/null || true

echo "$PORT" > /tmp/realvnc.port
echo "$OBF"  > /tmp/realvnc.obf
echo "$PW"   > /tmp/realvnc.pw
